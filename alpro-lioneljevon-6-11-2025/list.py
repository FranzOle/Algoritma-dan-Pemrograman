array_list = [10, 20, 30, 40, 50, 60]
print(array_list[0])  # Mengakses elemen pertama
print(array_list[3])  # Mengakses elemen ke-4
print(array_list[-1])  # Mengakses elemen terakhir

for item in range (len(array_list)):
    print(f'Elemen ke-{item} : {array_list[item]}')
    
